@login_required
def edit_product(request, id):
    try:
        profile = request.user.userprofile
        if profile.role != "Seller":
            return redirect("home")
    except UserProfile.DoesNotExist:
        return redirect("home")

    product = get_object_or_404(Product, id=id, seller=request.user)

    if request.method == "POST":
        product.name = request.POST.get("name")
        product.category = request.POST.get("category")
        product.description = request.POST.get("description")
        product.price = request.POST.get("price")
        product.stock = request.POST.get("stock")
        product.plastic_saving_weight = request.POST.get("plastic_saving_weight")
        product.co2_saving_weight = request.POST.get("co2_saving_weight")
        product.is_premium = request.POST.get("is_premium") == "on"
        product.save()

        image = request.FILES.get("image")
        if image:
            # Remove old images
            product.images.all().delete()
            ProductImage.objects.create(
                product=product,
                image=image
            )

        messages.success(request, f"Product '{product.name}' updated successfully.")
        return redirect("my_products")

    categories = Product.CATEGORY_CHOICES
    return render(request, "seller/edit_product.html", {
        "product": product,
        "categories": categories
    })

