@login_required
def manage_orders(request):
    try:
        profile = request.user.userprofile
        if profile.role != "Seller":
            return redirect("home")
    except UserProfile.DoesNotExist:
        return redirect("home")

    from Customer_app.models import Order
    orders = Order.objects.filter(items__product__seller=request.user).distinct().order_by('-created_at')
    
    orders_data = []
    for order in orders:
        seller_items = order.items.filter(product__seller=request.user)
        seller_total = sum(item.price * item.quantity for item in seller_items)
        orders_data.append({
            'order': order,
            'items': seller_items,
            'seller_total': seller_total,
            'customer_profile': order.customer.userprofile
        })
        
    return render(request, "seller/manage_orders.html", {"orders_data": orders_data})


@login_required
def update_order_status(request, order_id):
    try:
        profile = request.user.userprofile
        if profile.role != "Seller":
            return redirect("home")
    except UserProfile.DoesNotExist:
        return redirect("home")

    from Customer_app.models import Order
    order = get_object_or_404(Order, id=order_id)
    
    # Verify this order actually contains this seller's products
    has_product = order.items.filter(product__seller=request.user).exists()
    if not has_product:
        messages.error(request, "You are not authorized to update this order.")
        return redirect("manage_orders")

    if request.method == "POST":
        status = request.POST.get("status")
        if status in ['Pending', 'Processing', 'Shipped', 'Delivered', 'Cancelled']:
            order.status = status
            order.save()
            messages.success(request, f"Order #{order.id} status updated to '{status}'.")
        else:
            messages.error(request, "Invalid status choice.")
            
    return redirect("manage_orders")

