from django.shortcuts import render, redirect, get_object_or_404
from django.contrib.auth.decorators import login_required
from django.contrib import messages
from django.db.models import Sum, Count
from .models import Product, ProductImage
from Customer_app.models import UserProfile, OrderItem

@login_required
def dashboard(request):
    try:
        profile = request.user.userprofile
        if profile.role != "Seller":
            return redirect("home")
    except UserProfile.DoesNotExist:
        return redirect("home")

    # Seller metrics
    products = Product.objects.filter(seller=request.user)
    total_products = products.count()
    out_of_stock = products.filter(stock=0).count()
    
    # Calculate orders for products owned by this seller
    order_items = OrderItem.objects.filter(product__seller=request.user)
    total_sales = order_items.count()
    
    # Total revenue generated by selling products
    total_revenue = sum(item.price * item.quantity for item in order_items)
    
    # Collective eco impact made by this seller's products sold
    total_plastic_offset = sum(item.product.plastic_saving_weight * item.quantity for item in order_items if item.product)
    total_co2_offset = sum(item.product.co2_saving_weight * item.quantity for item in order_items if item.product)

    context = {
        "total_products": total_products,
        "out_of_stock": out_of_stock,
        "total_sales": total_sales,
        "total_revenue": total_revenue,
        "total_plastic_offset": total_plastic_offset,
        "total_co2_offset": total_co2_offset,
    }
    
    return render(request, "seller/dashboard.html", context)

@login_required
def add_product(request):
    try:
        profile = request.user.userprofile
        if profile.role != "Seller":
            return redirect("home")
    except UserProfile.DoesNotExist:
        return redirect("home")

    if request.method == "POST":
        name = request.POST.get("name")
        category = request.POST.get("category")
        description = request.POST.get("description")
        price = request.POST.get("price")
        stock = request.POST.get("stock")
        plastic_saving_weight = request.POST.get("plastic_saving_weight")
        co2_saving_weight = request.POST.get("co2_saving_weight")
        is_premium = request.POST.get("is_premium") == "on"

        product = Product.objects.create(
            seller=request.user,
            name=name,
            category=category,
            description=description,
            price=price,
            stock=stock,
            plastic_saving_weight=plastic_saving_weight,
            co2_saving_weight=co2_saving_weight,
            is_premium=is_premium
        )

        image = request.FILES.get("image")
        if image:
            ProductImage.objects.create(
                product=product,
                image=image
            )

        messages.success(request, f"Product '{name}' added successfully!")
        return redirect("my_products")

    categories = Product.CATEGORY_CHOICES
    return render(request, "seller/add_product.html", {"categories": categories})

